def make_svg():
    width = 24 * len(frames)
    height = 24
    
    svg = []
    svg.append(f'<svg width="{width*4}" height="{height*4}" viewBox="0 0 {width} {height}" xmlns="http://www.w3.org/2000/svg" style="image-rendering:pixelated; background:#121824;">')
    
    for f_idx, frame in enumerate(frames):
        offset_x = f_idx * 24
        for y, row in enumerate(frame):
            for x, char in enumerate(row):
                color = colors.get(char)
                if color:
                    svg.append(f'  <rect x="{offset_x + x}" y="{y}" width="1" height="1" fill="{color}" />')
                    
    svg.append('</svg>')
    
    with open('scratch/new_dolphin_sprites.svg', 'w') as f:
        f.write('\n'.join(svg))
    print("Generated scratch/new_dolphin_sprites.svg")

if __name__ == "__main__":
    make_svg()
